library(shiny)
library(plotly)
source("R/session.R")
testServer(function(input, output, session) {
  session$userData$plotlyShinyEventIDs <- paste0(c("plotly_selected", "plotly_click", "plotly_deselect"), "-test")
  selection <- link_plot_selection("test", session)
}, {
  selection$rows(data.frame(Gene = c("same", "same", "other"), Epitope = c("A", "B", "C")))
  session$flushReact()
  session$setInputs(`plotly_selected-test` = '[{"key":"2"},{"key":"1"}]')
  stopifnot(identical(selection$table()$Epitope, c("B", "A")))
  session$setInputs(`plotly_selected-test` = '[{"key":"3"}]')
  stopifnot(identical(selection$table()$Epitope, "C"))
  session$setInputs(`plotly_click-test` = '{"key":"1"}')
  stopifnot(identical(selection$table()$Epitope, c("C", "A")))
  session$setInputs(`plotly_deselect-test` = '{}')
  stopifnot(nrow(selection$table()) == 0)
  selection$rows(data.frame(Gene = "new", Epitope = "D"))
  session$flushReact()
  stopifnot(nrow(selection$table()) == 0)
})
cat("PASS lasso replaces rows, duplicate genes remain distinct, clicks toggle, deselection clears\n")
for (path in list.files("R", pattern = "\\.R$", full.names = TRUE)) invisible(parse(path))
