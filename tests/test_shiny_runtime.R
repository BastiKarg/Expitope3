source("R/runtime.R")
local({
  root <- tempfile("expitope-tests-")
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  expect_error <- function(expr) stopifnot(inherits(tryCatch({force(expr); NULL}, error = identity), "error"))
  path <- file.path(root, "tissue.tsv")
  writeLines(c("id\tsample-B\tsample-A", "ENSG1\t2.5\t7", "ENSG10\t99\t99"), path)
  expr <- read_gene_expression(path, "ENSG1")
  stopifnot(identical(expr$case_id, c("sample-B", "sample-A")), identical(expr$expression, c(2.5, 7)))
  expect_error(read_gene_expression(path, "ENSG"))
  queue <- file.path(root, "queue")
  stopifnot(identical(queue_listing(queue), "No jobs in queue"))
  scores <- file.path(root, "score.sc")
  writeLines(c("SCORE:\ttotal_score\tdescription\t", "SCORE:\t-1.5\ttarget"), scores)
  parsed <- read_structure_scores(scores)
  stopifnot(ncol(parsed) == 3, identical(parsed$total_score, -1.5), identical(parsed$description, "target"))
  job <- write_prediction_job("ACDEFGHIK", "HLA-A*02:01", 2, "test", 1, 1, queue_dir = queue)
  stopifnot(identical(readLines(job), "ACDEFGHIK HLA-A*02:01 2 test 1 1 normal_seq"), length(list.files(queue)) == 1)
  expect_error(write_prediction_job("INVALID", "HLA-A*02:01", 2, "test", 1, 1, queue_dir = queue))
  expect_error(write_prediction_job("ACDEFGHIK", "HLA-A*02:01", 2, "../escape", 1, 1, queue_dir = queue))
  dir.create(file.path(root, "mutated"))
  pdb <- file.path(root, "mutated", "test.pdb")
  writeLines(c("ATOM      1  CA  ALA B   3      11.000  12.000  13.000  1.00 20.00           C",
               "ATOM      2  CA  ALA B   5      11.000  12.000  13.000  1.00 20.00           C",
               "ATOM      3  CA  ALA A   8      11.000  12.000  13.000  1.00 20.00           C"), pdb)
  stopifnot(identical(list_pdb_files(root), "test.pdb"), identical(resolve_pdb_file("test.pdb", root), pdb),
            identical(pdb_residue_selection(pdb), "3:B or 5:B"))
  expect_error(resolve_pdb_file("../test.pdb", root))
  stopifnot(nrow(read_optional_table(file.path(root, "missing"), "id")) == 0)
  cat("Shiny runtime regression checks passed.\n")
})
