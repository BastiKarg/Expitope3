def calculate(epitopes, alpha):    ### changed to positions 1-9 only
    print("start TAP")
    for epitope in epitopes:
        for hit in epitope.protein_hits:
            seq = hit[0]
            if len(seq) > 8:
                pos9 = seq[8]
            else:
                pos9 = seq[len(seq) -1]
            c_score = tap_Matrix[pos9][3]
            n_score = tap_Matrix[seq[0]][0] + tap_Matrix[seq[1]][1] + tap_Matrix[seq[2]][2]  # BASTI kann das so berechnet werden?
            tap_score10 = pow(10, (c_score + (n_score * alpha)))  # According to Paper, TAP will happen if score is below 1. Maybe make this a threshold and not further include in score
            tap_score = (c_score + (n_score * alpha))

            tap_2004 = 0.5 * tap_matrix_2004[seq[0]][0] + 0.25 * tap_matrix_2004[seq[1]][1] + 0.2 * tap_matrix_2004[seq[2]][2] + 0.25 * tap_matrix_2004[seq[6]][6] + tap_matrix_2004[pos9][8]

            hit.extend((tap_score,tap_score10,tap_2004))
